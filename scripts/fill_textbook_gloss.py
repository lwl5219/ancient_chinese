def split_tokens(tokens: list[dict]) -> list[dict]:
    out = []
    for tok in tokens:
        if tok.get("punct") or len(tok.get("t") or "") <= 1:
            out.append(tok)
            continue
        pys = (tok.get("py") or "").split()
        if len(pys) != len(tok["t"]):
            pys = [""] * len(tok["t"])
        for trad, simp, py in zip(tok["t"], tok["s"], pys):
            out.append({
                "t": trad,
                "s": simp,
                "py": py,
                "ctx": tok.get("ctx") or "",
                "pos": "",
                "extra": "",
                "level": tok.get("level") or "dict",
            })
    return out


def apply_phrases(hans: str, slots: list[dict]) -> None:
    taken = [False] * len(slots)
    phrases = sorted(PHRASES, key=lambda item: len(item[0]), reverse=True)
    for phrase, glosses in phrases:
        if len(glosses) != len(phrase):
            raise SystemExit("短语长度不对：%s" % phrase)
        start = 0
        while True:
            found = hans.find(phrase, start)
            if found < 0:
                break
            if not any(taken[found + i] for i in range(len(phrase))):
                for i, (gloss, py) in enumerate(glosses):
                    slot = slots[found + i]
                    if gloss and not slot["locked"]:
                        slot["ctx"] = gloss
                    if py:
                        slot["py"] = py
                    slot["hit"] = True
                    taken[found + i] = True
            start = found + len(phrase)


def grammatical(ch: str, prev: str, nxt: str, end: bool) -> str:
    if ch == "之":
        if prev in "久顷" and end:
            return "凑足音节。"
        if end:
            return "它，指代前面的人或事物。"
        if nxt in "于乎":
            return "他、它，指前面的人或事物。"
        if prev == "何" or (prev and nxt in "有谓"):
            return "的。有时帮助把宾语提前。"
        return "的。"
    if ch == "而":
        if nxt in "不无未":
            return "却。"
        if prev and nxt:
            return "就、然后。连接两个动作或两种性状。"
        return "连词，连接前后两项。"
    if ch == "以":
        if prev in "可足以无是":
            return "用来。"
        if nxt in "为":
            return "认。"
        return "用、拿。"
    if ch == "也":
        if end:
            return "句末语气词，表示判断或肯定。"
        return "句中语气词，表示停顿。"
    if ch == "其":
        if nxt and nxt not in "所":
            return "他的、它的，或那。"
        return "他、它，或其中。"
    if ch == "者":
        return "……的人，或……的事物。"
    if ch == "于":
        if prev in "甚青寒重大于":
            return "比。"
        return "在、向、对。"
    if ch == "为":
        if prev == "以":
            return "是。"
        if nxt in "之":
            return "做。"
        return "做、是、成为。"
    if ch == "所":
        return "与后面的动词组成名词性结构。"
    if ch == "见" and prev in "而被":
        return "被。"
    if ch == "见" and nxt in "义":
        return "同“现”，显露。"
    if ch == "见" and prev == "请":
        return "拜见。"
    if ch == "已" and prev == "以" and end:
        return "停止。"
    if ch == "故" and nxt in "乡人国园":
        return "旧。"
    if ch == "若" and prev in "见":
        return "你。"
    if ch == "与" and end:
        return "同“欤”，吗。"
    if ch == "夫" and (not prev or prev in "且若今故"):
        return "句首语气词。"
    if ch == "名" and prev == "则":
        return "用作动词，出名。"
    if ch == "上" and (prev == "登" or nxt in "山车青天"):
        return "向上、登上。"
    if ch == "耳" and end:
        return "而已。"
    if ch == "云" and end:
        return "语气词，有“据说如此”的意思。"
    return ""


def fill_tokens(tokens: list[dict], pid: str) -> None:
    tokens = tokens
    han_slots = []
    for index, tok in enumerate(tokens):
        if tok.get("punct"):
            continue
        ch = tok.get("s") or ""
        if len(ch) != 1:
            continue
        locked = bool((tok.get("ctx") or "").strip())
        han_slots.append({
            "tok": tok,
            "index": index,
            "ctx": tok.get("ctx") or "",
            "py": "",
            "locked": locked,
            "hit": False,
        })
    hans = "".join(item["tok"]["s"] for item in han_slots)
    apply_phrases(hans, han_slots)
    for pos, item in enumerate(han_slots):
        tok = item["tok"]
        if item["locked"]:
            continue
        if not item["hit"]:
            prev = hans[pos - 1] if pos else ""
            nxt = hans[pos + 1] if pos + 1 < len(hans) else ""
            end = item["index"] + 1 >= len(tokens) or (
                tokens[item["index"] + 1].get("punct") and tokens[item["index"] + 1].get("s") in "。！？；"
            )
            gloss = grammatical(tok["s"], prev, nxt, end)
            if not gloss:
                gloss = SENSES.get(tok["s"]) or ""
            if not gloss:
                raise SystemExit("没有释义：%s（%s）" % (tok["s"], pid))
            item["ctx"] = gloss
        tok["ctx"] = item["ctx"]
        if item["py"]:
            tok["py"] = item["py"]
        tok["level"] = "sentence"


def main() -> None:
    grades = load_grades()
    missing = []
    # 文章
    for path in sorted((ROOT / "data" / "articles").glob("*.json")):
        if len(path.stem) != 6:
            continue
        art = json.loads(path.read_text(encoding="utf-8"))
        if art["id"] not in grades:
            continue
        for para in art["paragraphs"]:
            for sent in para["sentences"]:
                try:
                    fill_tokens(sent["tokens"], art["id"])
                except SystemExit as exc:
                    missing.append(str(exc))
        path.write_text(json.dumps(art, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    books = {
        "tang": ROOT / "data" / "tang.json",
        "ci": ROOT / "data" / "songci.json",
        "ke": ROOT / "data" / "ke.json",
    }
    for kind, path in books.items():
        data = json.loads(path.read_text(encoding="utf-8"))
        for piece in data["pieces"]:
            if piece["id"] not in grades:
                continue
            for line in piece["lines"]:
                line["tokens"] = split_tokens(line["tokens"])
                try:
                    fill_tokens(line["tokens"], piece["id"])
                except SystemExit as exc:
                    missing.append(str(exc))
        path.write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    if missing:
        raise SystemExit("\n".join(missing[:30]))
    print("filled grade pieces", len(grades))


if __name__ == "__main__":
    main()
