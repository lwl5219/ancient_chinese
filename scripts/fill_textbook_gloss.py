def load_senses() -> dict[str, str]:
    senses = {}
    for name in ("gloss_a.txt", "gloss_b.txt"):
        for line in (ROOT / "scripts" / name).read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            ch, gloss = line.split("\t", 1)
            senses[ch] = gloss
    return senses


